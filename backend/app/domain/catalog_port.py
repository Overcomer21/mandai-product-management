"""Feature-specific application boundary: no framework/database imports."""
from typing import Protocol, Any

class CatalogPort(Protocol):
    def catalog_categories(self, **kwargs: Any) -> Any: ...
    def catalog_count(self, **kwargs: Any) -> Any: ...
    def catalog(self, **kwargs: Any) -> Any: ...
    def product_detail(self, **kwargs: Any) -> Any: ...
    def admin_products_count(self, **kwargs: Any) -> Any: ...
    def admin_products_categories(self, **kwargs: Any) -> Any: ...
    def admin_products_stats(self, **kwargs: Any) -> Any: ...
    def admin_list(self, **kwargs: Any) -> Any: ...
    def admin_detail(self, **kwargs: Any) -> Any: ...
    def create_product(self, **kwargs: Any) -> Any: ...
    def edit_product(self, **kwargs: Any) -> Any: ...
    def delete_product(self, **kwargs: Any) -> Any: ...
